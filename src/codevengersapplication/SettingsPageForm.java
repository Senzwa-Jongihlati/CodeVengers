    private void btnChangePasswordActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnChangePasswordActionPerformed
        // TODO add your handling code here:
        // Get passwords from the fields
        String newPassword = new String(edtNewPassword.getPassword());
        String confirmPassword = new String(edtConfirmPassword.getPassword());

        if (edtNewPassword.getPassword().length != 0){
            // Check if they match
            if(!newPassword.equals(confirmPassword)) {
                JOptionPane.showMessageDialog(
                    null,
                    "Passwords do not match. Please try again.",
                    "Error",
                    JOptionPane.ERROR_MESSAGE
                );
            } else {
                // Ask for confirmation
                int result = JOptionPane.showConfirmDialog(
                    null,
                    "Are you sure you want to change your password?",
                    "Confirm Password Change",
                    JOptionPane.YES_NO_OPTION
                );

                if(result == JOptionPane.YES_OPTION) {
                    try {
                        // Connect to database
                        String url = "jdbc:mysql://localhost:3306/dsdatabase"; // your DB name
                        String user = "root"; // your MySQL username
                        String password = "Parklane01$";  // your MySQL password if any

                        conn = DriverManager.getConnection(url, user, password);
                        // Prepare SQL query
                        String sql = "UPDATE users SET password = ? WHERE User_Id = ?";
                        PreparedStatement pst = conn.prepareStatement(sql);
                        pst.setString(1, newPassword); // new password
                        pst.setInt(2, currentUser.getUserId()); // user ID

                        int rowsUpdated = pst.executeUpdate();

                        if(rowsUpdated > 0) {
                            // Show success message
                            JOptionPane.showMessageDialog(
                                null,
                                "Your password has been updated successfully!",
                                "Success",
                                JOptionPane.INFORMATION_MESSAGE
                            );

                            // Clear password fields
                            edtNewPassword.setText("");
                            edtConfirmPassword.setText("");
                        } else {
                            JOptionPane.showMessageDialog(
                                null,
                                "Password update failed. Please try again.",
                                "Error",
                                JOptionPane.ERROR_MESSAGE
                            );
                        }
                        pst.close();
                    } catch(SQLException ex) {
                        ex.printStackTrace();
                        JOptionPane.showMessageDialog(
                            null,
                            "Database error: " + ex.getMessage(),
                            "Error",
                            JOptionPane.ERROR_MESSAGE
                        );
                    }
                } 
                try { if (conn != null) conn.close(); } catch (SQLException e) {}

            }
        }
        else{
            JOptionPane.showMessageDialog(this, "Please enter a password first","Error",JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnChangePasswordActionPerformed
        
