    private void btnSaveProfileInfoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveProfileInfoActionPerformed
        int confirm = JOptionPane.showConfirmDialog(
            this,
            "Are you sure you want to update your information?",
            "Confirm Update",
            JOptionPane.YES_NO_OPTION,
            JOptionPane.QUESTION_MESSAGE
        );    
        if (confirm == JOptionPane.YES_OPTION){
            // TODO add your handling code here:
            String newFullName = edtFullName.getText().trim();
            String newEmail = edtEmail.getText().trim();

            // Update the currentUser object
            currentUser.setFullName(newFullName);
            currentUser.setEmail(newEmail);

            Connection conn = null;
            PreparedStatement pstmt = null;            
            try {
                // Connect to database
                String url = "jdbc:mysql://localhost:3306/dsdatabase"; // your DB name
                String user = "root"; // your MySQL username
                String password = "Parklane01$";  // your MySQL password if any

                conn = DriverManager.getConnection(url, user, password);

                // SQL UPDATE query
                String sql = "UPDATE users SET Full_name = ?, Email = ? WHERE User_ID = ?";
                pstmt = conn.prepareStatement(sql);
                pstmt.setString(1, newFullName);
                pstmt.setString(2, newEmail);
                pstmt.setInt(3, currentUser.getUserId());

                int rowsUpdated = pstmt.executeUpdate();

                if (rowsUpdated > 0) {
                    JOptionPane.showMessageDialog(this, 
                        "Your changes have been saved successfully!", 
                        "Success", 
                        JOptionPane.INFORMATION_MESSAGE);
                } else {
                    JOptionPane.showMessageDialog(this, 
                        "No changes were made. Please try again.", 
                        "Warning", 
                        JOptionPane.WARNING_MESSAGE);
                }

            } catch (SQLException ex) {
                JOptionPane.showMessageDialog(this, 
                    "Error while saving changes: " + ex.getMessage(), 
                    "Database Error", 
                    JOptionPane.ERROR_MESSAGE);
                ex.printStackTrace();
            } finally {
                // Close resources
                try { if (pstmt != null) pstmt.close(); } catch (SQLException e) {}
                try { if (conn != null) conn.close(); } catch (SQLException e) {}
            } 
        }
        else{
            JOptionPane.showMessageDialog(this, 
                "Update cancelled.", 
                "Cancelled", 
                JOptionPane.INFORMATION_MESSAGE);            
        }
    }//GEN-LAST:event_btnSaveProfileInfoActionPerformed

